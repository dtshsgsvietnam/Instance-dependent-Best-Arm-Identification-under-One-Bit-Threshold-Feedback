"""Compare theorem SHAPE with empirical q_{1-3eta}, not a certified numeric bound.

Requires a results directory already generated by the selected test case.
"""
from __future__ import annotations
import argparse, json, sys
from pathlib import Path
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from onebit_bai.report import u_remainder,e_remainder

def main():
    p=argparse.ArgumentParser()
    p.add_argument('--results',required=True)
    p.add_argument('--method',choices=['u_raw','e_companion'],required=True)
    p.add_argument('--eta',type=float,default=.05)
    p.add_argument('--empirical-C',type=float,help='A DATA-FITTED illustrative coefficient, not a theorem constant')
    a=p.parse_args();root=Path(a.results)
    conf=json.loads((root/'config.json').read_text()); o=json.loads((root/'oracles.json').read_text())
    table=pd.read_csv(root/'summary.csv');table=table[(table.method==a.method)&(table.stop_rate==1)].copy()
    if table.empty:raise SystemExit('No fully observed cells: refuse quantile comparisons on censoring')
    gamma=o['onebit_gamma'];L=table.log1d.to_numpy();baseline=L/gamma
    qcol=f'q{int(round(100*(1-3*a.eta))):02}'
    if qcol not in table:raise SystemExit(f'{qcol} absent; regenerate report with --eta {a.eta}')
    q=table[qcol].to_numpy()
    shape=np.array([u_remainder(float(l),1/gamma,a.eta) if a.method=='u_raw'
                else e_remainder(float(l),len(conf['mus']),a.eta) for l in L])
    fig,ax=plt.subplots(figsize=(8,5))
    order=np.argsort(L)
    ax.plot(L[order],q[order],marker='o',label=f'empirical {qcol} (completed trajectories only)')
    ax.plot(L[order],baseline[order],linestyle='--',label='T*log(1/delta)')
    if a.empirical_C is not None:
        ax.plot(L[order],(baseline+a.empirical_C*shape)[order],marker='.',
                label='empirical fitted C × theorem-shaped remainder (NOT proved)')
    ax.set_xlabel('log(1/delta)');ax.set_ylabel('Stopping time / empirical quantile')
    ax.set_title(f'{a.method}: sample tail and theorem-shaped scale');ax.legend()
    fig.tight_layout();dest=root/f'{a.method}_bound_shape_vs_quantiles.png';fig.savefig(dest,dpi=160)
    print('Created:',dest)
    print('NOTE: no numerical theoretical bound is evaluated: constants are existential.')
if __name__=='__main__':main()
